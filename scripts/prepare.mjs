// Generates one SPFx web part per entry in pages.json (see scripts/pages.mjs). Runs before every
// build and start, so the HTML pages stay the single source of truth:
//   src/generated/pages/<key>.ts           <- the page: markup (no scripts) + runPage() (see codegen.mjs)
//   src/generated/mount.ts                 <- host/mount.js: iframe mounting (shared with the local harness)
//   src/webparts/<key>/<Key>WebPart.ts     <- a thin subclass of src/PageWebPart.ts
//   src/webparts/<key>/<Key>WebPart.manifest.json
//   config/config.json                     <- one bundle per page
// The page sources are plain JS; they are emitted as .ts with @ts-nocheck so the SPFx TypeScript build
// compiles and bundles them unchanged. Nothing runs as inline script in SharePoint, so pages work under its CSP.
import { readFile, writeFile, mkdir, rm } from "node:fs/promises";
import path from "node:path";
import { banner, pageModule } from "./codegen.mjs";
import { SP_DIR, ROOT_DIR, loadPages, className, bundleName } from "./pages.mjs";

const GENERATED = path.join(SP_DIR, "src", "generated");
const WEBPARTS = path.join(SP_DIR, "src", "webparts");
const json = (v) => JSON.stringify(v, null, 2) + "\n";

let pages;
try { pages = await loadPages(); }
catch (e) { console.error(`[prepare] ${e.message}`); process.exit(1); }

await rm(GENERATED, { recursive: true, force: true });
await rm(WEBPARTS, { recursive: true, force: true });
await mkdir(path.join(GENERATED, "pages"), { recursive: true });
await writeFile(path.join(GENERATED, "mount.ts"), banner(true) + (await readFile(path.join(SP_DIR, "host", "mount.js"), "utf8")));

const bundles = {};
for (const p of pages) {
  let source;
  try { source = pageModule(await readFile(path.join(ROOT_DIR, p.file), "utf8"), { ts: true }); }
  catch (e) { console.error(`[prepare] ${p.file}: ${e.message}`); process.exit(1); }
  await writeFile(path.join(GENERATED, "pages", `${p.key}.ts`), source);

  const cls = className(p.key), dir = path.join(WEBPARTS, p.key);
  await mkdir(dir, { recursive: true });
  await writeFile(path.join(dir, `${cls}.ts`),
    `// GENERATED by scripts/prepare.mjs from pages.json (${p.file}). Do not edit.\n` +
    `import { PageWebPart, type IPageModule } from '../../PageWebPart';\n` +
    `import * as page from '../../generated/pages/${p.key}';\n\n` +
    `export default class ${cls} extends PageWebPart {\n` +
    `  protected get page(): IPageModule { return page; }\n` +
    `}\n`);
  await writeFile(path.join(dir, `${cls}.manifest.json`), json({
    $schema: "https://developer.microsoft.com/json-schemas/spfx/client-side-web-part-manifest.schema.json",
    id: p.id,
    alias: cls,
    componentType: "WebPart",
    version: "*",
    manifestVersion: 2,
    requiresCustomScript: false,
    supportedHosts: ["SharePointFullPage", "SharePointWebPart"],
    supportsFullBleed: true,
    supportsThemeVariants: true,
    preconfiguredEntries: [{
      groupId: "5c03119e-3074-46fd-976b-c60198311f70", // Advanced
      group: { default: "Advanced" },
      title: { default: p.title },
      description: { default: p.description || p.title },
      officeFabricIconFontName: p.icon,
      properties: {},
    }],
  }));
  bundles[bundleName(p.key)] = {
    components: [{ entrypoint: `./lib/webparts/${p.key}/${cls}.js`, manifest: `./src/webparts/${p.key}/${cls}.manifest.json` }],
  };
}

await writeFile(path.join(SP_DIR, "config", "config.json"), json({
  $schema: "https://developer.microsoft.com/json-schemas/spfx-build/config.2.0.schema.json",
  version: "2.0",
  bundles,
  externals: {},
  localizedResources: {},
}));

console.log(`[prepare] ${pages.length} web part(s): ${pages.map((p) => `${p.title} (${p.file})`).join(", ")}`);
